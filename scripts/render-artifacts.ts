import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { contextSectionLabels, reviewerTaskHead, thermosWorkflow } from "../packages/core/src/content.ts";
import {
	renderClaudeAgent,
	renderClaudeRunCommand,
	renderClaudeShimCommand,
	renderCodexThermosSkill,
	renderDeepseekHarnessPayload,
	renderDeepseekHarnessSkill,
	renderPiAgent,
} from "../packages/core/src/render.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const piProviders = ["nico", "gotgenes", "tintinweb"] as const;
const reviewerKinds = ["deep", "quality"] as const;

export const piPromptsModulePath = "packages/pi-thermos/src/generated/prompts.ts";

export function renderPiPromptsModule(): string {
	return [
		"// @generated by scripts/render-artifacts.ts. Do not edit.",
		"// biome-ignore-all format: the generated prompt text stays on one line",
		`export const thermosWorkflow = ${JSON.stringify(thermosWorkflow)};`,
		`export const reviewerTaskHead = ${JSON.stringify(reviewerTaskHead)};`,
		`export const contextSectionLabels = [${contextSectionLabels.map((label) => JSON.stringify(label)).join(", ")}];`,
		"",
	].join("\n");
}

const artifacts: Array<[path: string, content: string]> = [
	["packages/codex-thermos/skills/thermos/SKILL.md", renderCodexThermosSkill()],
	["packages/claude-thermos/commands/run.md", renderClaudeRunCommand()],
	["packages/claude-thermos/shims/thermos.md", renderClaudeShimCommand()],
	["packages/claude-thermos/agents/thermo-nuclear-review-subagent.md", renderClaudeAgent("deep")],
	["packages/claude-thermos/agents/thermo-nuclear-code-quality-review-subagent.md", renderClaudeAgent("quality")],
	...piProviders.flatMap((provider) =>
		reviewerKinds.map(
			(kind) =>
				[
					`packages/pi-thermos/agents/${provider}/thermo-nuclear-${kind === "deep" ? "review" : "code-quality-review"}-subagent.md`,
					renderPiAgent(kind, provider),
				] as [string, string],
		),
	),
	["packages/deepseek-harness-thermos/skill/thermos/SKILL.md", renderDeepseekHarnessSkill()],
	[
		"packages/deepseek-harness-thermos/skill/thermos/references/deep-review-payload.md",
		renderDeepseekHarnessPayload("deep"),
	],
	[
		"packages/deepseek-harness-thermos/skill/thermos/references/code-quality-payload.md",
		renderDeepseekHarnessPayload("quality"),
	],
];

function writeArtifact(path: string, content: string): void {
	const target = join(root, path);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, content, "utf8");
}

if (import.meta.main) {
	for (const [path, content] of artifacts) {
		writeArtifact(path, content);
	}
	writeArtifact(piPromptsModulePath, renderPiPromptsModule());

	console.log(`Rendered ${artifacts.length} host artifacts and the Pi prompt module.`);
}
